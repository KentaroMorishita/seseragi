import "@js-joda/timezone"
import { ZoneRulesProvider } from "@js-joda/core"
import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"
import "./timezone-bundle"

type PackedDatabase = {
  version: string
  zones: string[]
  links: string[]
}

const root = resolve(import.meta.dir, "..")
const provider = ZoneRulesProvider as typeof ZoneRulesProvider & {
  getTzdbData(): PackedDatabase
}
const data = provider.getTzdbData()
if (data.version !== "2025b") throw new Error("expected tzdb 2025b")
const zones = data.zones.map((packed) => {
  const [id, , offsets, indices, untils] = packed.split("|")
  return `${id}|${offsets}|${indices}|${untils}`
})
const names = new Map<string, number>()
data.zones.forEach((packed, index) => {
  names.set(packed.split("|")[0]!, index)
})
for (const link of data.links) {
  const [target, alias] = link.split("|")
  const index = names.get(target!)
  if (index === undefined) throw new Error(`unknown timezone link: ${link}`)
  names.set(alias!, index)
}
const digest = createHash("sha256")
  .update(await readFile(resolve(root, "runtime/ts/src/timezone-rules.js")))
  .digest("hex")
const source = `// Generated by scripts/generate-native-timezones.ts from @js-joda/timezone.
// Timezone data: IANA tzdb 2025b, public domain.
const NATIVE_TIME_ZONE_VERSION: &str = ${JSON.stringify(data.version)};
#[cfg(test)]
const NATIVE_TIME_ZONE_BUNDLE_SHA256: &str = ${JSON.stringify(digest)};
#[rustfmt::skip]
const NATIVE_TIME_ZONE_PACKED: &[&str] = &[
${zones.map((zone) => `    ${JSON.stringify(zone)},`).join("\n")}
];
#[rustfmt::skip]
const NATIVE_TIME_ZONE_NAMES: &[(&str, usize)] = &[
${[...names]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([name, index]) => `    (${JSON.stringify(name)}, ${index}),`)
  .join("\n")}
];
`
const target = resolve(
  root,
  "crates/seseragi-native-runtime/src/timezone_data.rs"
)
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source) {
    throw new Error(
      "native timezone data is stale; run bun scripts/generate-native-timezones.ts"
    )
  }
} else {
  await writeFile(target, source)
}
