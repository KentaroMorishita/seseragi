// Writes the Homebrew formula for one release.
//
//   bun scripts/homebrew-formula.ts <version> <checksum-dir> <output>
//
// <checksum-dir> holds the `.sha256` files attached to the GitHub Release,
// such as `seseragi-v0.61.178-darwin-arm64.tar.gz.sha256`. The formula takes
// every checksum from them, so it never needs editing by hand.

import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const repository = "https://github.com/KentaroMorishita/seseragi"

/** The archives a release ships for macOS and Linux. */
export const formulaTargets = [
  "darwin-arm64",
  "darwin-x64",
  "linux-x64",
] as const
export type FormulaTarget = (typeof formulaTargets)[number]

export function archiveName(version: string, target: FormulaTarget): string {
  return `seseragi-v${version}-${target}.tar.gz`
}

/** Reads the checksum of each archive from its `.sha256` file. */
export function readChecksums(
  version: string,
  directory: string
): Record<FormulaTarget, string> {
  const checksums = {} as Record<FormulaTarget, string>
  for (const target of formulaTargets) {
    const file = join(directory, `${archiveName(version, target)}.sha256`)
    const checksum = readFileSync(file, "utf8").trim().split(/\s+/)[0] ?? ""
    if (!/^[0-9a-f]{64}$/.test(checksum)) {
      throw new Error(`${file} does not hold a SHA-256 checksum`)
    }
    checksums[target] = checksum
  }
  return checksums
}

export function renderFormula(
  version: string,
  checksums: Record<FormulaTarget, string>
): string {
  if (!/^[0-9]+(\.[0-9]+)*$/.test(version)) {
    throw new Error(`invalid version: ${version}`)
  }
  const archive = (target: FormulaTarget) =>
    [
      `      url "${repository}/releases/download/v${version}/${archiveName(version, target)}"`,
      `      sha256 "${checksums[target]}"`,
    ].join("\n")
  return `# This file is generated by scripts/homebrew-formula.ts in
# ${repository} for each release. Do not edit it by hand.
class Seseragi < Formula
  desc "CLI and language server for the Seseragi programming language"
  homepage "${repository}"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
${archive("darwin-arm64")}
    end
    on_intel do
${archive("darwin-x64")}
    end
  end

  on_linux do
    on_intel do
${archive("linux-x64")}
    end
  end

  def install
    bin.install "seseragi", "seseragi-lsp"
    # The license notice covers Unicode data inside the binaries.
    prefix.install "UNICODE-LICENSE" if File.exist?("UNICODE-LICENSE")
  end

  def caveats
    <<~EOS
      Running Seseragi programs needs Bun 1.4.4 or later:
        https://bun.sh/docs/installation
      Update with \`brew upgrade seseragi\`.
    EOS
  end

  test do
    assert_match "seseragi #{version} ", shell_output("#{bin}/seseragi --version")
    system bin/"seseragi-lsp", "--version-json"
  end
end
`
}

if (import.meta.main) {
  const [version, directory, output] = process.argv.slice(2)
  if (!version || !directory || !output) {
    console.error(
      "usage: bun scripts/homebrew-formula.ts <version> <checksum-dir> <output>"
    )
    process.exit(2)
  }
  const normalized = version.replace(/^v/, "")
  writeFileSync(
    output,
    renderFormula(normalized, readChecksums(normalized, directory))
  )
}
