use super::*;

pub(super) fn http_client_interface() -> ModuleInterface {
    let module = "std/http";
    let build_error = named("HttpBuildError");
    let method = named("Method");
    let method_value = external_type("Method", "std/http::Method", module, "Method", Vec::new());
    let status = named("Status");
    let status_value = external_type("Status", "std/http::Status", module, "Status", Vec::new());
    let headers = named("Headers");
    let headers_value = external_type(
        "Headers",
        "std/http::Headers",
        module,
        "Headers",
        Vec::new(),
    );
    let url = named("HttpUrl");
    let request = named("Request");
    let response = named("Response");
    let body = |environment: InterfaceType, failure: InterfaceType| {
        named_with("Body", vec![environment, failure])
    };
    let event = named("HttpEvent");
    let version_value = external_type(
        "HttpVersion",
        "std/http::HttpVersion",
        module,
        "HttpVersion",
        Vec::new(),
    );
    let response_head_value = named("ResponseHead");
    let limit = named("HttpBodyLimit");
    let bytes = external_type(
        "Bytes",
        "std/bytes::Bytes",
        "std/bytes",
        "Bytes",
        Vec::new(),
    );
    let build_result =
        |success: InterfaceType| named_with("Either", vec![build_error.clone(), success]);
    standard_interface(
        module,
        vec![
            type_export(module, "HttpClient", 0, "opaque-type"),
            type_export(module, "Method", 0, "opaque-type"),
            type_export(module, "Status", 0, "opaque-type"),
            type_export(module, "Headers", 0, "opaque-type"),
            type_export(module, "HttpUrl", 0, "opaque-type"),
            type_export(module, "Request", 0, "opaque-type"),
            type_export(module, "Response", 0, "opaque-type"),
            type_export(module, "Body", 2, "opaque-type"),
            type_export(module, "HttpBodyLimit", 0, "opaque-type"),
            opaque_adt_type_export(module, "HttpVersion", []),
            constructor_export(module, "HttpVersion", "HttpVersionUnknown", [], None),
            constructor_export(module, "HttpVersion", "Http1_0", [], None),
            constructor_export(module, "HttpVersion", "Http1_1", [], None),
            constructor_export(module, "HttpVersion", "Http2", [], None),
            constructor_export(module, "HttpVersion", "Http3", [], None),
            public_record_type_export(
                module,
                "ResponseHead",
                [
                    required("version", version_value),
                    required("status", status_value),
                    required("headers", headers_value.clone()),
                ],
            ),
            opaque_adt_type_export(module, "HttpEvent", []),
            constructor_export(
                module,
                "HttpEvent",
                "InformationalResponse",
                [],
                Some(response_head_value.clone()),
            ),
            constructor_export(
                module,
                "HttpEvent",
                "ResponseStarted",
                [],
                Some(response_head_value),
            ),
            constructor_export(
                module,
                "HttpEvent",
                "ResponseBodyChunk",
                [],
                Some(bytes.clone()),
            ),
            constructor_export(
                module,
                "HttpEvent",
                "ResponseTrailers",
                [],
                Some(headers_value.clone()),
            ),
            opaque_adt_type_export(module, "HttpBuildError", []),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHttpUrl",
                [],
                Some(record([required("offset", named("Int"))])),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "UnsupportedHttpScheme",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "HttpUrlContainsUserInfo",
                [],
                None,
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "HttpUrlContainsFragment",
                [],
                None,
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHttpMethod",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHeaderName",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHeaderValue",
                [],
                Some(record([
                    required("name", named("String")),
                    required("offset", named("Int")),
                ])),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "ManagedHttpHeader",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHttpStatus",
                [],
                Some(named("Int")),
            ),
            constructor_export(
                module,
                "HttpBuildError",
                "InvalidHttpBodyLimit",
                [],
                Some(named("Int")),
            ),
            opaque_adt_type_export(module, "HttpError", []),
            constructor_export(
                module,
                "HttpError",
                "HttpDnsFailure",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpConnectionFailure",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpTlsFailure",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpProtocolFailure",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpRequestBodyFailure",
                [],
                Some(named("String")),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpRequestLengthMismatch",
                [],
                Some(record([
                    required("declared", named("Int")),
                    required("actual", named("Int")),
                ])),
            ),
            constructor_export(
                module,
                "HttpError",
                "HttpResponseBodyLimitExceeded",
                [],
                Some(record([required("limitBytes", named("Int"))])),
            ),
            constructor_export(module, "HttpError", "HttpClientUnavailable", [], None),
            value_export(module, "get", method_value.clone()),
            value_export(module, "head", method_value.clone()),
            value_export(module, "post", method_value.clone()),
            value_export(module, "put", method_value.clone()),
            value_export(module, "patch", method_value.clone()),
            value_export(module, "delete", method_value.clone()),
            value_export(module, "options", method_value.clone()),
            value_export(module, "connect", method_value.clone()),
            value_export(module, "trace", method_value),
            function_export(
                module,
                "customMethod",
                [],
                Vec::new(),
                vec![named("String")],
                build_result(method.clone()),
            ),
            function_export(
                module,
                "methodText",
                [],
                Vec::new(),
                vec![method],
                named("String"),
            ),
            function_export(
                module,
                "status",
                [],
                Vec::new(),
                vec![named("Int")],
                build_result(status.clone()),
            ),
            function_export(
                module,
                "statusCode",
                [],
                Vec::new(),
                vec![status.clone()],
                named("Int"),
            ),
            function_export(
                module,
                "isInformational",
                [],
                Vec::new(),
                vec![status.clone()],
                named("Bool"),
            ),
            function_export(
                module,
                "isSuccess",
                [],
                Vec::new(),
                vec![status.clone()],
                named("Bool"),
            ),
            function_export(
                module,
                "isRedirection",
                [],
                Vec::new(),
                vec![status.clone()],
                named("Bool"),
            ),
            function_export(
                module,
                "isClientError",
                [],
                Vec::new(),
                vec![status.clone()],
                named("Bool"),
            ),
            function_export(
                module,
                "isServerError",
                [],
                Vec::new(),
                vec![status],
                named("Bool"),
            ),
            function_export(
                module,
                "parseUrl",
                [],
                Vec::new(),
                vec![named("String")],
                build_result(url.clone()),
            ),
            function_export(
                module,
                "renderUrl",
                [],
                Vec::new(),
                vec![url.clone()],
                named("String"),
            ),
            value_export(module, "emptyHeaders", headers_value),
            function_export(
                module,
                "appendHeader",
                [],
                Vec::new(),
                vec![named("String"), named("String"), headers.clone()],
                build_result(headers.clone()),
            ),
            function_export(
                module,
                "setHeader",
                [],
                Vec::new(),
                vec![named("String"), named("String"), headers.clone()],
                build_result(headers.clone()),
            ),
            function_export(
                module,
                "removeHeader",
                [],
                Vec::new(),
                vec![named("String"), headers.clone()],
                headers.clone(),
            ),
            function_export(
                module,
                "headerValues",
                [],
                Vec::new(),
                vec![named("String"), headers.clone()],
                named_with("Array", vec![named("String")]),
            ),
            function_export(
                module,
                "headerEntries",
                [],
                Vec::new(),
                vec![headers.clone()],
                named_with(
                    "Array",
                    vec![InterfaceType::Tuple {
                        elements: vec![named("String"), named("String")],
                    }],
                ),
            ),
            function_export(
                module,
                "request",
                [],
                Vec::new(),
                vec![named("Method"), url],
                request.clone(),
            ),
            function_export(
                module,
                "withRequestHeader",
                [],
                Vec::new(),
                vec![named("String"), named("String"), request.clone()],
                build_result(request.clone()),
            ),
            function_export(
                module,
                "withoutRequestHeader",
                [],
                Vec::new(),
                vec![named("String"), request.clone()],
                request.clone(),
            ),
            function_export(
                module,
                "emptyBody",
                ["R", "E"],
                Vec::new(),
                vec![named("Unit")],
                body(named("R"), named("E")),
            ),
            function_export(
                module,
                "bytesBody",
                ["R", "E"],
                Vec::new(),
                vec![bytes.clone()],
                body(named("R"), named("E")),
            ),
            function_export(
                module,
                "streamBody",
                ["R", "E"],
                Vec::new(),
                vec![external_type(
                    "Stream",
                    "std/stream::Stream",
                    "std/stream",
                    "Stream",
                    vec![named("R"), named("E"), bytes.clone()],
                )],
                body(named("R"), named("E")),
            ),
            function_export(
                module,
                "exchange",
                ["R", "E"],
                Vec::new(),
                vec![body(named("R"), named("E")), request.clone()],
                external_type(
                    "Stream",
                    "std/stream::Stream",
                    "std/stream",
                    "Stream",
                    vec![
                        InterfaceType::RequirementMerge {
                            operands: vec![
                                named("R"),
                                record([required("httpClient", named("HttpClient"))]),
                            ],
                        },
                        named_with("Either", vec![named("E"), named("HttpError")]),
                        event,
                    ],
                ),
            ),
            function_export(
                module,
                "bodyLimit",
                [],
                Vec::new(),
                vec![named("Int")],
                build_result(limit.clone()),
            ),
            function_export(
                module,
                "defaultBodyLimit",
                [],
                Vec::new(),
                vec![named("Unit")],
                limit.clone(),
            ),
            effect_function_export(
                module,
                "sendBytes",
                [],
                Vec::new(),
                vec![limit.clone(), bytes.clone(), request.clone()],
                effect(
                    record([required("httpClient", named("HttpClient"))]),
                    named("HttpError"),
                    response.clone(),
                ),
            ),
            effect_function_export(
                module,
                "sendEmpty",
                [],
                Vec::new(),
                vec![limit, request],
                effect(
                    record([required("httpClient", named("HttpClient"))]),
                    named("HttpError"),
                    response.clone(),
                ),
            ),
            function_export(
                module,
                "responseStatus",
                [],
                Vec::new(),
                vec![response.clone()],
                named("Status"),
            ),
            function_export(
                module,
                "responseHeaders",
                [],
                Vec::new(),
                vec![response.clone()],
                headers,
            ),
            function_export(
                module,
                "responseBody",
                [],
                Vec::new(),
                vec![response],
                bytes,
            ),
            function_export(
                module,
                "errorMessage",
                [],
                Vec::new(),
                vec![named("HttpError")],
                named("String"),
            ),
        ],
    )
}
