use super::*;

pub(super) fn time_interface() -> ModuleInterface {
    let module = "std/time";
    let duration = named("Duration");
    let duration_result = named_with("Either", vec![named("DurationError"), duration.clone()]);
    let date = named("LocalDate");
    let time = named("LocalTime");
    let local = named("LocalDateTime");
    let offset = named("UtcOffset");
    let offset_date_time = named("OffsetDateTime");
    let zone = named("TimeZone");
    let zoned = named("ZonedDateTime");
    let date_result = |success| named_with("Either", vec![named("DateTimeError"), success]);
    let timezone_effect = |failure, success| {
        effect(
            record([required("timeZones", named("TimeZones"))]),
            failure,
            success,
        )
    };
    let mut exports = vec![
        type_export(module, "Instant", 0, "opaque-type"),
        type_export(module, "Duration", 0, "opaque-type"),
        opaque_adt_type_export(module, "DurationError", []),
        constructor_export(
            module,
            "DurationError",
            "NegativeDuration",
            [],
            Some(named("Int")),
        ),
        constructor_export(module, "DurationError", "DurationOutsideRange", [], None),
        function_export(
            module,
            "zeroDuration",
            [],
            Vec::new(),
            vec![named("Unit")],
            duration.clone(),
        ),
        function_export(
            module,
            "nanoseconds",
            [],
            Vec::new(),
            vec![named("Int")],
            duration_result.clone(),
        ),
        function_export(
            module,
            "milliseconds",
            [],
            Vec::new(),
            vec![named("Int")],
            duration_result.clone(),
        ),
        function_export(
            module,
            "seconds",
            [],
            Vec::new(),
            vec![named("Int")],
            duration_result.clone(),
        ),
        function_export(
            module,
            "minutes",
            [],
            Vec::new(),
            vec![named("Int")],
            duration_result.clone(),
        ),
        function_export(
            module,
            "hours",
            [],
            Vec::new(),
            vec![named("Int")],
            duration_result,
        ),
        function_export(
            module,
            "toNanoseconds",
            [],
            Vec::new(),
            vec![duration.clone()],
            named("Int"),
        ),
        function_export(
            module,
            "addDuration",
            [],
            Vec::new(),
            vec![duration.clone(), duration],
            named_with("Either", vec![named("DurationError"), named("Duration")]),
        ),
        type_export(module, "LocalDate", 0, "opaque-type"),
        type_export(module, "LocalTime", 0, "opaque-type"),
        type_export(module, "LocalDateTime", 0, "opaque-type"),
        type_export(module, "UtcOffset", 0, "opaque-type"),
        type_export(module, "OffsetDateTime", 0, "opaque-type"),
        type_export(module, "TimeZone", 0, "opaque-type"),
        type_export(module, "ZonedDateTime", 0, "opaque-type"),
        type_export(module, "TimeZones", 0, "opaque-type"),
        opaque_adt_type_export(module, "DateTimeError", []),
        constructor_export(
            module,
            "DateTimeError",
            "InvalidDate",
            [],
            Some(record([
                required("year", named("Int")),
                required("month", named("Int")),
                required("day", named("Int")),
            ])),
        ),
        constructor_export(
            module,
            "DateTimeError",
            "InvalidTime",
            [],
            Some(record([
                required("hour", named("Int")),
                required("minute", named("Int")),
                required("second", named("Int")),
                required("nanosecond", named("Int")),
            ])),
        ),
        constructor_export(
            module,
            "DateTimeError",
            "InvalidUtcOffsetSeconds",
            [],
            Some(named("Int")),
        ),
        constructor_export(
            module,
            "DateTimeError",
            "InvalidDateTimeText",
            [],
            Some(record([required("offset", named("Int"))])),
        ),
        opaque_adt_type_export(module, "TimeZoneError", []),
        constructor_export(
            module,
            "TimeZoneError",
            "UnknownTimeZone",
            [],
            Some(named("String")),
        ),
        constructor_export(
            module,
            "TimeZoneError",
            "TimeZoneDatabaseUnavailable",
            [],
            Some(named("String")),
        ),
        constructor_export(
            module,
            "TimeZoneError",
            "TimeZoneDatabaseVersionMismatch",
            [],
            Some(record([
                required("required", named("String")),
                required("actual", named("String")),
            ])),
        ),
        opaque_adt_type_export(module, "LocalResolution", []),
        constructor_export(module, "LocalResolution", "Unique", [], Some(zoned.clone())),
        constructor_export(
            module,
            "LocalResolution",
            "Ambiguous",
            [],
            Some(record([
                required("earlier", zoned.clone()),
                required("later", zoned.clone()),
            ])),
        ),
        constructor_export(
            module,
            "LocalResolution",
            "Gap",
            [],
            Some(record([
                required("transition", named("Instant")),
                required("offsetBefore", offset.clone()),
                required("offsetAfter", offset.clone()),
            ])),
        ),
        function_export(
            module,
            "localDate",
            [],
            Vec::new(),
            vec![named("Int"), named("Int"), named("Int")],
            date_result(date.clone()),
        ),
        function_export(
            module,
            "localTime",
            [],
            Vec::new(),
            vec![named("Int"), named("Int"), named("Int"), named("Int")],
            date_result(time.clone()),
        ),
        function_export(
            module,
            "localDateTime",
            [],
            Vec::new(),
            vec![date.clone(), time.clone()],
            local.clone(),
        ),
        function_export(
            module,
            "utcOffset",
            [],
            Vec::new(),
            vec![named("Int")],
            date_result(offset.clone()),
        ),
        function_export(
            module,
            "parseLocalDate",
            [],
            Vec::new(),
            vec![named("String")],
            date_result(date.clone()),
        ),
        function_export(
            module,
            "parseLocalTime",
            [],
            Vec::new(),
            vec![named("String")],
            date_result(time.clone()),
        ),
        function_export(
            module,
            "parseLocalDateTime",
            [],
            Vec::new(),
            vec![named("String")],
            date_result(local.clone()),
        ),
        function_export(
            module,
            "parseOffsetDateTime",
            [],
            Vec::new(),
            vec![named("String")],
            date_result(offset_date_time.clone()),
        ),
        function_export(
            module,
            "formatLocalDate",
            [],
            Vec::new(),
            vec![date],
            named("String"),
        ),
        function_export(
            module,
            "formatLocalTime",
            [],
            Vec::new(),
            vec![time],
            named("String"),
        ),
        function_export(
            module,
            "formatLocalDateTime",
            [],
            Vec::new(),
            vec![local.clone()],
            named("String"),
        ),
        function_export(
            module,
            "formatOffsetDateTime",
            [],
            Vec::new(),
            vec![offset_date_time.clone()],
            named("String"),
        ),
        function_export(
            module,
            "atOffset",
            [],
            Vec::new(),
            vec![offset, named("Instant")],
            offset_date_time.clone(),
        ),
        function_export(
            module,
            "offsetInstant",
            [],
            Vec::new(),
            vec![offset_date_time.clone()],
            named("Instant"),
        ),
        function_export(
            module,
            "offsetLocalDateTime",
            [],
            Vec::new(),
            vec![offset_date_time],
            local.clone(),
        ),
        function_export(
            module,
            "databaseVersion",
            [],
            Vec::new(),
            vec![named("Unit")],
            timezone_effect(named("Never"), named("String")),
        ),
        function_export(
            module,
            "loadTimeZone",
            [],
            Vec::new(),
            vec![named("String")],
            timezone_effect(named("TimeZoneError"), zone.clone()),
        ),
        function_export(
            module,
            "timeZoneId",
            [],
            Vec::new(),
            vec![zone.clone()],
            named("String"),
        ),
        function_export(
            module,
            "timeZoneVersion",
            [],
            Vec::new(),
            vec![zone.clone()],
            named("String"),
        ),
        function_export(
            module,
            "atTimeZone",
            [],
            Vec::new(),
            vec![named("Instant"), zone.clone()],
            zoned.clone(),
        ),
        function_export(
            module,
            "resolveLocal",
            [],
            Vec::new(),
            vec![local, zone.clone()],
            named("LocalResolution"),
        ),
        function_export(
            module,
            "zonedInstant",
            [],
            Vec::new(),
            vec![zoned.clone()],
            named("Instant"),
        ),
        function_export(
            module,
            "zonedLocalDateTime",
            [],
            Vec::new(),
            vec![zoned.clone()],
            named("LocalDateTime"),
        ),
        function_export(
            module,
            "zonedOffset",
            [],
            Vec::new(),
            vec![zoned.clone()],
            named("UtcOffset"),
        ),
        function_export(module, "zonedTimeZone", [], Vec::new(), vec![zoned], zone),
    ];
    standard_interface(module, std::mem::take(&mut exports))
}
